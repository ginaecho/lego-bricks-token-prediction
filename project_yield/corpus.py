"""The historical record the value and impact heads are fitted on.

One :class:`Engagement` is one use case that was actually delivered, with what
it was signed at, whether it landed, who worked on it and how long it took.
This is the training set for everything except the token head — the token head
keeps its own evidence, the 39 real agent runs in
``experiments/train_runs.jsonl``, and is not re-derived here.

Where the data comes from
-------------------------
The corpus shipped with the prototype is **synthetic** and says so in every
record (``provenance``). It is generated by ``experiments/make_engagements.py``
from a documented latent process, seeded, and committed so the demo is
reproducible. It exists to prove the machinery end to end; it is not evidence
about any real client, and no conclusion about pricing should be drawn from it.

Replacing it with the real thing is a one-file change: point
:func:`load_engagements` at an extract with the same columns. The intended
source is a Fabric Lakehouse table over delivery and CRM records — see
``docs/product-prototype.md`` for the query and the column mapping.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence

from .usecase import GOALS, INDUSTRIES, UseCase, normalise_counts


@dataclass(frozen=True)
class Engagement:
    """One delivered use case and its realised outcomes."""

    id: str
    title: str
    client: str
    industry: str
    goal: str
    counts: Dict[str, int]
    context_bytes: int
    # -- outcomes, as realised -------------------------------------------
    contract_value: float
    won: bool
    architect_days: float
    engineer_days: float
    pm_days: float
    calendar_days: float
    # -- lineage ---------------------------------------------------------
    parent_id: Optional[str] = None
    sibling_ids: Sequence[str] = ()
    # -- bookkeeping -----------------------------------------------------
    started: str = ""
    provenance: str = "synthetic"
    held_out: bool = False

    @property
    def total_units(self) -> int:
        return sum(self.counts.values())

    @property
    def staff_days(self) -> float:
        return self.architect_days + self.engineer_days + self.pm_days

    def observed(self, outcome: str) -> float:
        """The realised value of one outcome, by slug."""
        if outcome == "win_probability":
            return 1.0 if self.won else 0.0
        return float(getattr(self, outcome))

    def as_usecase(self) -> UseCase:
        """The same engagement viewed as an input, for lineage and similarity."""
        return UseCase(
            id=self.id, title=self.title, industry=self.industry, goal=self.goal,
            counts=dict(self.counts), context_bytes=self.context_bytes,
            parent_id=self.parent_id, sibling_ids=list(self.sibling_ids),
            client=self.client, encoder="historical",
        )


def default_corpus_path() -> str:
    """The committed engagement corpus that ships with the package."""
    return os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "experiments", "engagements.jsonl")


def load_engagements(path: Optional[str] = None) -> List[Engagement]:
    """Read the corpus, validating the columns the heads depend on.

    Validation is strict on purpose. A record with an unknown industry or a
    missing outcome does not fail loudly at fit time — it quietly biases one
    head — so it is rejected here, where the message can name the row.
    """
    path = path or default_corpus_path()
    out: List[Engagement] = []
    with open(path, encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.strip()
            if not line or line.startswith("//"):
                continue
            d = json.loads(line)
            try:
                eng = Engagement(
                    id=str(d["id"]), title=str(d.get("title", "")),
                    client=str(d.get("client", "")),
                    industry=str(d["industry"]), goal=str(d["goal"]),
                    counts=normalise_counts(d["counts"]),
                    context_bytes=int(d.get("context_bytes", 0)),
                    contract_value=float(d["contract_value"]),
                    won=bool(d["won"]),
                    architect_days=float(d["architect_days"]),
                    engineer_days=float(d["engineer_days"]),
                    pm_days=float(d["pm_days"]),
                    calendar_days=float(d["calendar_days"]),
                    parent_id=(str(d["parent_id"]) if d.get("parent_id") else None),
                    sibling_ids=tuple(str(s) for s in (d.get("sibling_ids") or [])),
                    started=str(d.get("started", "")),
                    provenance=str(d.get("provenance", "synthetic")),
                    held_out=bool(d.get("held_out", False)),
                )
            except KeyError as exc:
                raise ValueError(
                    f"{os.path.basename(path)}:{lineno}: record is missing "
                    f"required column {exc.args[0]!r}") from None
            if eng.industry not in INDUSTRIES:
                raise ValueError(f"{os.path.basename(path)}:{lineno}: "
                                 f"unknown industry {eng.industry!r}")
            if eng.goal not in GOALS:
                raise ValueError(f"{os.path.basename(path)}:{lineno}: "
                                 f"unknown goal {eng.goal!r}")
            out.append(eng)
    if not out:
        raise ValueError(f"{path} contains no engagement records")
    return out


def summarise(engagements: Sequence[Engagement]) -> str:
    """A short census of the corpus, for the top of any report."""
    n = len(engagements)
    won = sum(1 for e in engagements if e.won)
    cont = sum(1 for e in engagements if e.parent_id)
    held = sum(1 for e in engagements if e.held_out)
    provs = sorted({e.provenance for e in engagements})
    values = sorted(e.contract_value for e in engagements)
    return (f"{n} engagements ({held} held out) · {won / n:.0%} succeeded · "
            f"{cont / n:.0%} continuations · value "
            f"${values[0]:,.0f}-${values[-1]:,.0f} · provenance: "
            + ", ".join(provs))
